function logLandingTemplateStatus(){
    const summarize = (el) => ({
        exists: !!el,
        id: el ? el.id : null,
        childCount: el ? el.children.length : 0,
        hasContent: el ? el.innerHTML.trim().length > 0 : false
    })
    loggerLanding.info('[LandingTemplate] newsContainer', summarize(newsContainer))
    loggerLanding.info('[LandingTemplate] schematicsContainer', summarize(schematicsContainer))
    loggerLanding.info('[LandingTemplate] schematicsInstalledPanel', summarize(schematicsInstalledPanel))
}

function logOverlayState(label, el){
    if(!el){
        loggerLanding.warn(`[LandingOverlay] ${label} missing`)
        return
    }
    const rect = el.getBoundingClientRect()
    const style = window.getComputedStyle(el)
    loggerLanding.info(`[LandingOverlay] ${label}`, {
        display: style.display,
        position: style.position,
        top: style.top,
        visibility: style.visibility,
        opacity: style.opacity,
        pointerEvents: style.pointerEvents,
        rect: { x: rect.x, y: rect.y, w: rect.width, h: rect.height }
    })
}
